"""tools/make_audio.py: records every string in tools/audio-list.json as audio/<id>.mp3
and writes audio/manifest.js, which the app reads to play recordings instead of system voices.
Only missing files are recorded; files no longer in the list are deleted.

  pip install edge-tts
  node tools/list-audio.js > tools/audio-list.json
  python tools/make_audio.py

Runs automatically on GitHub (.github/workflows/audio.yml)."""
import asyncio, hashlib, json, os, sys

import edge_tts

VOICE = os.environ.get("MASUME_VOICE", "ja-JP-NanamiNeural")
# Characters the voice service will not read on their own: record a sound-alike instead.
SAY = {"ゔ": "ヴ"}
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
AUDIO = os.path.join(ROOT, "audio")


def file_id(text):
    return hashlib.md5((VOICE + "|" + text).encode("utf-8")).hexdigest()[:12]


async def record(text, path, sem):
    async with sem:
        for attempt in range(4):
            try:
                await edge_tts.Communicate(SAY.get(text, text), VOICE).save(path + ".part")
                if os.path.getsize(path + ".part") > 500:
                    os.replace(path + ".part", path)
                    return True
            except Exception as e:  # network hiccup or rate limit: wait and retry
                print(f"  retry {attempt + 1} for {text}: {e}", file=sys.stderr)
            await asyncio.sleep(2 * (attempt + 1))
        if os.path.exists(path + ".part"):
            os.remove(path + ".part")
        print(f"FAILED: {text}", file=sys.stderr)
        return False


async def main():
    os.makedirs(AUDIO, exist_ok=True)
    with open(os.path.join(ROOT, "tools", "audio-list.json"), encoding="utf-8") as f:
        texts = json.load(f)
    ids = {t: file_id(t) for t in texts}
    todo = [t for t in texts if not os.path.exists(os.path.join(AUDIO, ids[t] + ".mp3"))]
    print(f"{len(texts)} strings, {len(todo)} to record with {VOICE}")
    sem = asyncio.Semaphore(6)
    await asyncio.gather(*(record(t, os.path.join(AUDIO, ids[t] + ".mp3"), sem) for t in todo))

    keep = {i + ".mp3" for i in ids.values()}
    for name in os.listdir(AUDIO):
        if name.endswith(".mp3") and name not in keep:
            os.remove(os.path.join(AUDIO, name))
    have = {t: i for t, i in sorted(ids.items()) if os.path.exists(os.path.join(AUDIO, i + ".mp3"))}
    with open(os.path.join(AUDIO, "manifest.js"), "w", encoding="utf-8", newline="\n") as f:
        f.write("/* audio/manifest.js: generated by tools/make_audio.py. Do not edit. Voice: " + VOICE + " */\n")
        f.write("window.MS = window.MS || {};\nMS.audio = " + json.dumps(have, ensure_ascii=False, indent=0) + ";\n")
    print(f"manifest: {len(have)} recordings")
    missing = [t for t in texts if t not in have]
    if missing:  # not fatal: the app uses the browser voice for these
        print("::warning::No recording for: " + " ".join(missing))


asyncio.run(main())
